// Ports prompts/chatgpt/trend-analysis.md (steps 1-2) into a fillable template.
export function buildTrendAnalysisPrompt({ description, platform, genreLabel, characterRef }) {
  return `너는 유튜브 AI 콘텐츠 트렌드 분석가다.

아래는 최근 바이럴 중인 트렌드/포맷/사운드다.
[출처 플랫폼]: ${platform || '미지정'}
[트렌드 설명]: ${description || '(설명을 입력하세요)'}

1단계 - 이 트렌드를 구조적으로 분석해라:
1. 왜 지금 바이럴한가 (시의성/감정/유머/공감 포인트)
2. 핵심 후킹 구조 (몇 초에 무슨 일이 일어나는가)
3. 반복되는 편집/연출 패턴 (컷 타이밍, 반전 위치, 사운드 싱크 포인트)
4. 시청자가 참여/공유하고 싶어지는 이유
5. 이 트렌드의 예상 수명 (며칠~몇 주)

2단계 - 위 구조를 아래 우리 콘텐츠로 재해석해라:
- 우리 장르: ${genreLabel || '미지정'}
- 기존 캐릭터/세계관: ${characterRef || '(없음 - 신규 캐릭터 없이 비주얼 중심으로 구성)'}
- 조건:
  1. 원본 음원/영상을 그대로 쓰지 않는다 - 후킹 타이밍과 감정 곡선만 차용한다.
  2. 기존 캐릭터/세계관을 그대로 재사용한다 (신규 캐릭터 설계 금지).
  3. 24~48시간 내 제작 가능한 분량(15~30초 Shorts)으로 구성한다.

출력: 로그라인 1줄 + 왜 이 재해석이 우리 채널에 통할지 근거 3줄을 먼저 제시하고,
이어서 3단계(씬 생성) 입력으로 쓸 수 있도록 전체 개요를 정리해라.`;
}
